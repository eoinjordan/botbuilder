def design(out: dict) -> list:
    ev = out["design_evidence"]
    drawn, comb = out["presets"]["drawn"], out["presets"]["comb_feet"]

    def lift(name):
        t = ev[name]["one_foot_test"]
        parts = []
        for side in ("left", "right"):
            s = t[side]
            parts.append(f"{side} foot lifted: " + (f"falls {s['fell_how']}" if s["fell"] else
                         f"clear of the floor {round(100 * s['lifted_foot_clear_of_floor_fraction'])} percent of the hold, "
                         f"median clearance {s['lifted_foot_clearance_mm']} mm, other foot carries {s['load_on_other_foot_fraction']} of the weight"))
        return "; ".join(parts)

    md = ["## Design changes and the evidence", "",
          "Why the drawn robot cannot take a slow step. A foot can only be lifted and held if the centre of mass is over the other foot.",
          "The legs have hip roll, hip pitch and knee pitch. With a sole flat on the floor and no ankle, the leg above it is upright in the",
          "frontal plane, so the hips cannot move sideways over a foot; rolling the stance hip only tilts the torso about an axis that passes",
          "close to the centre of mass. The centre of mass therefore stays midway between soles whose inner edges are 124 mm apart.", "",
          f"- Slow lift test, drawn: {lift('drawn')}.",
          "- So on the drawn geometry a foot leaves the floor only while the robot is falling back onto it. The search found exactly that:",
          f"  swings of {drawn['walk']['nominal'].get('median_swing_s')} s with the knees at their torque limit "
          f"{round(100 * drawn['walk']['nominal'].get('time_at_torque_limit_fraction', 0))} percent of the time.", ""]
    if "rocker_feet" in ev:
        md += [f"- Curved (rocker) soles moved inboard, tried and rejected: {lift('rocker_feet')}. A body on a rocker of radius R with its centre of mass at height h",
               "  above the floor and offset D from the sole's lowest line comes to rest tilted by D / (R - h) with the contact point R D / (R - h) from that line,",
               "  which is always further than D: the sole would have to reach past the centreline. A rocker smooths a dynamic gait; it does not give a static step.", ""]
    md += ["The smallest change found that gives a real step needs no new actuator and touches one part, the sole plate of each shin:", "",
           "- Each sole becomes a rail under the leg with fingers that reach across the centreline, between the fingers of the other sole",
           "  (left: two fingers, right: one between them). The centre of mass, which cannot be moved, is then inside the support of either foot alone.",
           f"- Slow lift test, comb feet: {lift('comb_feet')}.",
           f"- Mass {comb['stand']['mass_kg']} kg against {drawn['stand']['mass_kg']} kg. The joints, their ranges, the hips, the deck and the board are unchanged.",
           "- The gait that goes with it is statically stable: the body glides forward while each foot in turn is lifted toes up, carried one stride and set down.",
           "  The feet stay level by turning the knee against the hip; the hip roll servos level the body when one leg is longer than the other.",
           "- Plausibility as a printed part: fingers 14 mm wide, 5 mm thick, 74 mm long. A finger carrying the whole weight at its tip would see about 6 MPa in bending",
           "  and sag about 1.5 mm in PLA (E 3 GPa); a rib along the top would halve that. Gap between neighbouring fingers 26 mm fore and aft, 10 mm at the tips;",
           "  the simulation collides the two legs with each other and the gait keeps them apart. The soles are checked against the floor and the other leg only.",
           "- What it does not fix: there is still no yaw joint, so turning is by scrubbing; the long fingers put a twisting load on the knee horn and the",
           "  cable-tied servos that the model's single spring per joint only roughly represents; and the swing must be toes up, so the heel end stays short.", "",
           "Considered and not needed: moving the hips, narrowing the stance, lowering the controller board, a compliant ankle. None of them puts the centre of mass over",
           "one flat foot without also crossing the centreline. An ankle roll servo would, but all six servos are in use.", "",
           "Jump: no change to the printed parts makes it a jump. The limit is the servos: see the no-load bound in each jump section.",
           "A real jump needs a faster or stronger actuator, or a spring that is loaded slowly and released, which this kit does not have.", ""]
    return md


