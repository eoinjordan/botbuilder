"""URDF, MJCF and the joint table of the Microduck-look build.

Bodies carry the mass, centre of mass and inertia of their printed parts
(from the meshes), servos and boards. Each link collides with the floor only,
as one box round its solids; a foot collides as the convex slab under its
sole, web included; a comb foot as the slab under its sole and fingers
(microduck_look_comb.xml). Servos are position actuators that reach stall torque at
a 4 degree error, with damping of stall torque over no-load speed, as in
microduck/describe.py.
"""
from __future__ import annotations

import json

import numpy as np
from scipy.spatial import ConvexHull

from . import analyse, combfeet
from .model import JOINTS, ROOT, Robot

G = 9.80665
FLOOR_FRICTION = 0.6
JOINT_FRICTIONLOSS = 0.02
KP_SATURATION_DEG = 4.0
ARMATURE = {"SR431": 0.003, "SR311": 0.001, "M5_180": 0.0002}     # assumed reflected rotor inertia, kg m2
TARGET = ROOT / "robot" / "microduck-look"
REPORT = ROOT / "reports" / "microduck-look" / "assembly.json"
# Signal for each joint: two Braccio shields on two UNO Q boards take the twelve Braccio servos on the shield
# outputs M1 to M6 (pins 11, 10, 9, 6, 5, 3); the three small servos are on a 16 channel I2C driver.
CHANNELS = {
    "left_hip_yaw": ("board 1", "M1", 11), "left_hip_roll": ("board 1", "M2", 10), "left_hip_pitch": ("board 1", "M3", 9),
    "left_knee": ("board 1", "M4", 6), "left_ankle": ("board 1", "M5", 5), "neck_pitch": ("board 1", "M6", 3),
    "right_hip_yaw": ("board 2", "M1", 11), "right_hip_roll": ("board 2", "M2", 10), "right_hip_pitch": ("board 2", "M3", 9),
    "right_knee": ("board 2", "M4", 6), "right_ankle": ("board 2", "M5", 5), "head_pitch": ("board 2", "M6", 3),
    "head_yaw": ("driver", "channel 0", None), "head_roll": ("driver", "channel 1", None), "beak": ("driver", "channel 2", None),
}


def _f(values, digits=6) -> str:
    return " ".join(f"{float(v):.{digits}g}" for v in np.ravel(values))


def joint_table(robot: Robot, report: dict) -> dict:
    joints = {}
    for name in JOINTS:
        j = robot.joints[name]
        spec = robot.types[j.servo]
        lim = report["joint_ranges"][name]
        board, output, pin = CHANNELS[name]
        joints[name] = {
            "parent": j.parent, "child": j.child, "servo": j.servo,
            "anchor_m": [round(float(v) / 1000.0, 6) for v in j.anchor], "axis": [float(v) for v in j.axis],
            "min_deg": lim["min_deg"], "max_deg": lim["max_deg"], "original_range_deg": list(j.original_range),
            "torque_limit_nm": spec["torque"], "speed_limit_deg_s": spec["speed"], "armature_kgm2": ARMATURE[j.servo],
            "driven_by": board, "output": output, "pin": pin,
            "zero_deg": 90.0, "direction": 1,
        }
    stand = report["stand_pose"]["q_deg"]
    return {"generated_by": "scripts/run_look.py", "order": JOINTS, "joints": joints,
            "stand_pose_deg": {j: float(stand[j]) for j in JOINTS},
            "stand_trunk_height_m": report["stand_pose"]["trunk_height_m"],
            "neutral_trunk_height_m": round(-robot.floor_z / 1000.0, 5),
            "mass_kg": round(robot.mass_kg(), 4),
            "note": "zero_deg and direction are placeholders until the horns are fitted; no firmware reads this table yet"}


def link_box(robot: Robot, name: str):
    lo, hi = np.full(3, np.inf), np.full(3, -np.inf)
    for s in robot.links[name].solids:
        if s.kind == "horn":
            continue
        b = s.solid.bounding_box()
        lo, hi = np.minimum(lo, b[:3]), np.maximum(hi, b[3:])
    return lo, hi


def sole_slab(robot: Robot, side: str, thickness: float = 4.0) -> np.ndarray:
    """Corners of the convex slab under a sole, in the robot frame at the zero pose."""
    pts = analyse.sole_points(robot, side)
    hull = pts[ConvexHull(pts[:, :2]).vertices][:, :2]
    z = pts[:, 2].min()
    return np.vstack([np.c_[hull, np.full(len(hull), z)], np.c_[hull, np.full(len(hull), z + thickness)]])


def _origin(robot: Robot, name: str) -> np.ndarray:
    link = robot.links[name]
    return np.zeros(3) if link.joint is None else robot.joints[link.joint].anchor


def _inertial(robot: Robot, name: str):
    mass, com, inertia = robot.link_inertial(name)
    return mass / 1000.0, (com - _origin(robot, name)) / 1000.0, inertia * 1e-9


COLOUR = {"trunk": "0.93 0.92 0.87 1", "foot": "0.94 0.59 0.18 1", "beak": "0.94 0.59 0.18 1", "head": "0.93 0.92 0.87 1",
          "thigh": "0.93 0.92 0.87 1"}


def _rgba(name: str) -> str:
    for key, value in COLOUR.items():
        if name.endswith(key):
            return value
    return "0.24 0.26 0.29 1"


def mjcf(robot: Robot, table: dict, name: str = "microduck_look") -> str:
    out = ['<!-- Generated by scripts/run_look.py. Do not edit. Shapes adapted from the Microduck by Pollen Robotics, CC BY-NC-SA 4.0. -->',
           f'<mujoco model="{name}">',
           '  <compiler angle="radian" autolimits="true"/>',
           '  <option timestep="0.002" integrator="implicitfast"/>',
           '  <default>',
           f'    <geom friction="{FLOOR_FRICTION} 0.005 0.0001" contype="1" conaffinity="0" density="0"/>',
           '  </default>',
           '  <visual><global offwidth="960" offheight="720"/><headlight ambient="0.45 0.45 0.45" diffuse="0.6 0.6 0.6"/></visual>',
           '  <asset>',
           '    <texture type="skybox" builtin="gradient" rgb1="0.97 0.98 0.97" rgb2="0.80 0.87 0.84" width="64" height="384"/>',
           '    <texture name="grid" type="2d" builtin="checker" rgb1="0.93 0.95 0.94" rgb2="0.84 0.89 0.86" width="256" height="256"/>',
           '    <material name="grid" texture="grid" texrepeat="10 10" reflectance="0.05"/>']
    for side in ("left", "right"):
        slab = (sole_slab(robot, side) - _origin(robot, f"{side}_foot")) / 1000.0
        out.append(f'    <mesh name="{side}_sole" vertex="{_f(slab)}"/>')
    out += ['  </asset>', '  <worldbody>',
            '    <light pos="0.6 0.4 1.5" dir="-0.4 -0.3 -1" diffuse="0.5 0.5 0.5"/>',
            f'    <geom name="floor" type="plane" size="2 2 0.05" material="grid" contype="1" conaffinity="1" friction="{FLOOR_FRICTION} 0.005 0.0001"/>']

    def body(name: str, depth: int) -> None:
        link = robot.links[name]
        pad = "  " * depth
        origin = _origin(robot, name)
        if link.parent is None:
            out.append(f'{pad}<body name="{name}" pos="0 0 {table["neutral_trunk_height_m"]}">')
            out.append(f'{pad}  <freejoint name="root"/>')
        else:
            j = table["joints"][link.joint]
            pos = (origin - _origin(robot, link.parent)) / 1000.0
            damping = j["torque_limit_nm"] / np.radians(j["speed_limit_deg_s"])
            out.append(f'{pad}<body name="{name}" pos="{_f(pos)}">')
            out.append(f'{pad}  <joint name="{link.joint}" type="hinge" axis="{_f(j["axis"])}" range="{_f(np.radians([-90.0, 90.0]))}" '
                       f'damping="{damping:.5g}" armature="{j["armature_kgm2"]}" frictionloss="{JOINT_FRICTIONLOSS}"/>')
        mass, com, inertia = _inertial(robot, name)
        full = [inertia[0, 0], inertia[1, 1], inertia[2, 2], inertia[0, 1], inertia[0, 2], inertia[1, 2]]
        out.append(f'{pad}  <inertial pos="{_f(com)}" mass="{mass:.6g}" fullinertia="{_f(full)}"/>')
        lo, hi = link_box(robot, name)
        lo, hi = (lo - origin) / 1000.0, (hi - origin) / 1000.0
        if name.endswith("_foot"):
            side = name.split("_")[0]
            out.append(f'{pad}  <geom name="{name}_sole" type="mesh" mesh="{side}_sole" rgba="{_rgba(name)}"/>')
            lo[2] += 0.006
        out.append(f'{pad}  <geom name="{name}_box" type="box" pos="{_f((lo + hi) / 2)}" size="{_f((hi - lo) / 2)}" rgba="{_rgba(name)}"/>')
        for child in robot.order:
            if robot.links[child].parent == name:
                body(child, depth + 1)
        out.append(f'{pad}</body>')

    body("trunk", 2)
    out += ['  </worldbody>', '  <actuator>']
    for joint in JOINTS:
        j = table["joints"][joint]
        kp = j["torque_limit_nm"] / np.radians(KP_SATURATION_DEG)
        out.append(f'    <position name="{joint}" joint="{joint}" kp="{kp:.5g}" ctrlrange="{_f(np.radians([-90.0, 90.0]))}" '
                   f'forcerange="{-j["torque_limit_nm"]} {j["torque_limit_nm"]}"/>')
    out += ['  </actuator>', '  <sensor>']
    for joint in JOINTS:
        out.append(f'    <actuatorfrc name="{joint}_torque" actuator="{joint}"/>')
    stand = np.radians([table["stand_pose_deg"][j] for j in JOINTS])
    zeros = " ".join(["0"] * len(JOINTS))
    out += ['  </sensor>', '  <keyframe>',
            f'    <key name="neutral" qpos="0 0 {table["neutral_trunk_height_m"]} 1 0 0 0 {zeros}" ctrl="{zeros}"/>',
            f'    <key name="stand" qpos="0 0 {table["stand_trunk_height_m"]} 1 0 0 0 {_f(stand)}" ctrl="{_f(stand)}"/>',
            '  </keyframe>', '</mujoco>']
    return "\n".join(out) + "\n"


def urdf(robot: Robot, table: dict) -> str:
    out = ['<?xml version="1.0"?>',
           '<!-- Generated by scripts/run_look.py. Do not edit. Shapes adapted from the Microduck by Pollen Robotics, CC BY-NC-SA 4.0. -->',
           '<robot name="microduck_look">']
    for name in robot.order:
        mass, com, inertia = _inertial(robot, name)
        lo, hi = link_box(robot, name)
        origin = _origin(robot, name)
        lo, hi = (lo - origin) / 1000.0, (hi - origin) / 1000.0
        geom = f'<origin xyz="{_f((lo + hi) / 2)}" rpy="0 0 0"/><geometry><box size="{_f(hi - lo)}"/></geometry>'
        out.append(f'  <link name="{name}">')
        out.append(f'    <inertial><origin xyz="{_f(com)}" rpy="0 0 0"/><mass value="{mass:.6g}"/>'
                   f'<inertia ixx="{inertia[0, 0]:.6g}" ixy="{inertia[0, 1]:.6g}" ixz="{inertia[0, 2]:.6g}" '
                   f'iyy="{inertia[1, 1]:.6g}" iyz="{inertia[1, 2]:.6g}" izz="{inertia[2, 2]:.6g}"/></inertial>')
        out.append(f'    <visual>{geom}</visual>')
        for s in robot.links[name].solids:
            if s.file:
                m = np.array(next(p["print_to_robot"] for p in robot.p["parts"] if p["file"] == s.file), float)
                r = m[:3, :3]
                rpy = (np.arctan2(r[2, 1], r[2, 2]), -np.arcsin(np.clip(r[2, 0], -1.0, 1.0)), np.arctan2(r[1, 0], r[0, 0]))
                out.append(f'    <visual><origin xyz="{_f((m[:3, 3] - origin) / 1000.0)}" rpy="{_f(rpy)}"/><geometry>'
                           f'<mesh filename="../../stl/microduck-look/{s.file}" scale="0.001 0.001 0.001"/></geometry></visual>')
        out.append(f'    <collision>{geom}</collision>')
        out.append('  </link>')
    for joint in JOINTS:
        j = table["joints"][joint]
        pos = (robot.joints[joint].anchor - _origin(robot, j["parent"])) / 1000.0
        damping = j["torque_limit_nm"] / np.radians(j["speed_limit_deg_s"])
        out.append(f'  <joint name="{joint}" type="revolute">')
        out.append(f'    <parent link="{j["parent"]}"/><child link="{j["child"]}"/>')
        out.append(f'    <origin xyz="{_f(pos)}" rpy="0 0 0"/><axis xyz="{_f(j["axis"])}"/>')
        out.append(f'    <limit lower="{np.radians(j["min_deg"]):.6g}" upper="{np.radians(j["max_deg"]):.6g}" '
                   f'effort="{j["torque_limit_nm"]}" velocity="{np.radians(j["speed_limit_deg_s"]):.6g}"/>')
        out.append(f'    <dynamics damping="{damping:.5g}" friction="{JOINT_FRICTIONLOSS}"/>')
        out.append('  </joint>')
    out.append('</robot>')
    return "\n".join(out) + "\n"


def generate(robot: Robot | None = None) -> dict:
    with open(REPORT, encoding="utf-8") as handle:
        report = json.load(handle)
    robot = robot or Robot()
    table = joint_table(robot, report)
    TARGET.mkdir(parents=True, exist_ok=True)
    (TARGET / "joints.json").write_text(json.dumps(table, indent=1) + "\n", encoding="utf-8", newline="\n")
    (TARGET / "microduck_look.xml").write_text(mjcf(robot, table), encoding="utf-8", newline="\n")
    (TARGET / "microduck_look.urdf").write_text(urdf(robot, table), encoding="utf-8", newline="\n")
    if combfeet.have(robot.folder):
        # the same joints, limits and stand pose on the comb feet: the feet's shape, mass and sole differ
        comb = Robot(robot.folder, feet="comb")
        (TARGET / "microduck_look_comb.xml").write_text(mjcf(comb, table, "microduck_look_comb"), encoding="utf-8", newline="\n")
    return table
